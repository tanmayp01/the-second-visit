#!/usr/bin/env node
/**
 * Launch gate. Run before pointing the domain at the site:
 *
 *   SITE_URL=https://yourdomain.in PUBLIC_WEB3FORMS_KEY=... npm run launch-check
 *
 * It exits with an error until every launch requirement is met.
 */
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), 'utf8');
const problems = [];
const ok = [];
const check = (pass, good, bad) => (pass ? ok : problems).push(pass ? good : bad);

// 1. Custom domain
const siteUrl = process.env.SITE_URL || '';
check(
  /^https:\/\/[^/]+\.[a-z]{2,}$/i.test(siteUrl) && !/vercel\.app|netlify\.app|example/i.test(siteUrl),
  `Custom domain set: ${siteUrl}`,
  'SITE_URL must be the custom domain, e.g. https://thesecondvisit.in (not a vercel.app address).',
);

// 2. Favicon
check(
  existsSync(join(root, 'public/favicon.svg')) && existsSync(join(root, 'public/favicon.ico')) && existsSync(join(root, 'public/apple-touch-icon.png')),
  'Favicons present (svg, ico, apple-touch-icon).',
  'A favicon file is missing from public/.',
);

// 3. Legal pages
check(
  existsSync(join(root, 'src/pages/privacy.astro')) && existsSync(join(root, 'src/pages/terms.astro')),
  'Privacy Policy and Terms pages exist.',
  'Privacy Policy or Terms page is missing.',
);

// 4. No placeholders left in site.ts
const siteTs = read('src/config/site.ts');
const nulls = [...siteTs.matchAll(/^\s*(\w+):\s*null as/gm)].map((m) => m[1]);
check(nulls.length === 0, 'All content fields in site.ts are filled in.', `Still empty in src/config/site.ts: ${nulls.join(', ')}`);
check(!/previousRoles:\s*\[\]/.test(siteTs), 'Previous roles are filled in.', 'previousRoles in site.ts is empty.');

// 5. Form switched on
check(Boolean(process.env.PUBLIC_WEB3FORMS_KEY), 'Web3Forms key provided.', 'PUBLIC_WEB3FORMS_KEY is not set, so the enquiry form cannot send.');

// 6. Videos hosted on the site itself
const mediaTs = read('src/config/media.ts');
check(!/src:\s*'https?:/.test(mediaTs), 'Background videos are self-hosted.', 'Background videos still load from Pixabay. Download them into public/video/ and update media.ts.');

// 7. Stand-in photos replaced with real ones
const tempDir = join(root, 'src/assets/photos/temporary');
const tempLeft = existsSync(tempDir) ? readdirSync(tempDir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)) : [];
check(tempLeft.length === 0, 'No stand-in photos left.', `Stand-in AI photos still in src/assets/photos/temporary/: ${tempLeft.join(', ')}. Replace them with real photographs.`);

// 8. No "made with" badges, em dashes or emoji in what visitors see
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : /\.(astro|ts)$/.test(p) ? [p] : [];
});
const pages = walk(join(root, 'src'));
const text = pages.map((p) => readFileSync(p, 'utf8')).join('\n');
check(!/made with|built with|generated by|chatgpt|\bclaude\b/i.test(text), 'No "made with" or AI badges.', 'A "made with" or AI mention was found in a page.');
check(!/\u2014/.test(text), 'No em dashes in page copy.', 'An em dash was found in page copy.');
check(!/(?![\u00A9\u00AE\u2122])\p{Extended_Pictographic}/u.test(text), 'No emoji in pages.', 'An emoji was found in a page.');

for (const line of ok) console.log(`  ok    ${line}`);
for (const line of problems) console.log(`  TODO  ${line}`);
if (problems.length) {
  console.log(`\nNot ready to launch: ${problems.length} item(s) left.`);
  process.exit(1);
}
console.log('\nReady to launch.');
